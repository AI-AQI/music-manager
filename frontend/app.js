async function addDetailEditTag() {

    const input =
        $("detailEditTagInput");

    const value = normalizeTag(input.value);

    if (!value) {
        return;
    }

    if (state.editTags.includes(value)) {
        input.value = "";
        showToast("该 Tag 已添加");
        return;
    }

    state.editTags.push(value);
    state.editTagIds.push(null);

    input.value = "";

    renderDetailEditTags();

    // 保存音乐时后端会同步创建此前不存在的 Tag，并关联到当前音乐。
    await saveDetailEdit({
        tags: [...state.editTags],
        tagIds: [...state.editTagIds]
    });
}


async function saveDetailEdit(changes) {

    const id =
        state.selectedMusic.id;

    const music =
        await dbGet("music", id);

    if (!music) {
        return;
    }

    if (changes.name !== undefined) {

        music.name =
            changes.name;
    }

    if (changes.album !== undefined) {

        music.album =
            changes.album;

        // 单独编辑专辑名称代表手动覆盖；切换来源时由调用方指定来源。
        if (changes.albumSource === undefined) {
            music.albumSource = "manual";
        }
    }

    if (changes.albumSource !== undefined) {
        music.albumSource = changes.albumSource;
    }

    if (changes.artist !== undefined) {

        music.artist =
            changes.artist;
    }

    if (changes.genre !== undefined) {

        music.genre =
            changes.genre;
    }

    if (changes.year !== undefined) {

        music.year =
            changes.year;
    }

    if (changes.tags !== undefined) {

        music.tags =
            changes.tags;
        music.tagIds = changes.tagIds || [];
    }

    music.updatedAt =
        Date.now();

    await dbPut("music", music);


    /* 同步播放器 */

    const p = state.player;

    if (
        p.music &&
        p.music.id === music.id
    ) {

        p.music = music;

        renderBarMeta();
    }


    /* 刷新 */

    await updateCounts();

    await renderSidebarTags();

    await render();

    await openDetail(music.id);

    showToast("已保存");
}


/* =========================================================
   文件定位
========================================================= */

async function revealInFinder(music) {

    if (!music.path) {

        showToast(
            "这个音乐没有关联文件路径"
        );

        return;
    }

    try {

        // 应用保持打开时，Finder 仍可能刚刚移动了文件；访问前再解析一次书签。
        await invoke("sync_library_locations");
        music = (await dbGet("music", music.id)) || music;

        const exists =
            await invoke("file_exists", {
                path: music.path
            });

        if (!exists) {

            showToast(
                "文件不存在，可能已经被移动或删除"
            );

            return;
        }

        await __TAURI__.opener.revealItemInDir(
            music.path
        );

    } catch (error) {

        console.error(error);

        showToast(
            "无法在 Finder 中定位"
        );
    }
}


