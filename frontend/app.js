function renderBarMeta() {

    const p = state.player;

    const music = p.music;

    if (!music) {

        $("playerTitle").textContent =
            "未在播放";

        $("playerMeta").textContent =
            "—";

        return;
    }

    if (p.segment) {

        $("playerTitle").textContent =
            "◈ 片段：";

    } else {

        $("playerTitle").textContent =
            "";
    }

    $("playerTitle").textContent +=
        music.name || "未命名";

    const meta = [];

    if (p.segment) {

        meta.push(
            formatTime(p.segment.start) +
            " - " +
            formatTime(p.segment.end)
        );
    }

    if (music.album) {
        meta.push("专辑：" + music.album);
    }

    $("playerMeta").textContent =
        meta.join(" · ") ||
        (music.duration
            ? formatTime(music.duration)
            : "—");
}


function updateBarTime() {

    const a = getAudio();

    const p = state.player;

    const dur =
        Number.isFinite(a.duration)
            ? a.duration
            : 0;

    const cur =
        Number.isFinite(a.currentTime)
            ? a.currentTime
            : 0;

    $("playerTime").textContent =
        formatTime(cur) +
        " / " +
        formatTime(dur || (p.music && p.music.duration) || 0);

    if (!p.seeking) {

        $("playerSeek").value =
            dur
                ? Math.round(cur / dur * 1000)
                : 0;
    }
}


