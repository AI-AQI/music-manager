function setupDropZone() {

    const zone = $("dropZone");

    const modalOpen = () =>
        !importModal.classList.contains("hidden");

    const zoneAdd = () =>
        zone.classList.add("dragover");

    const zoneRemove = () =>
        zone.classList.remove("dragover");


    const appWindow =
        __TAURI__.window.getCurrentWindow();

    appWindow.onDragDropEvent(
        async event => {

            if (!modalOpen()) {
                return;
            }

            if (event.type === "over") {

                zoneAdd();

            } else if (
                event.type === "leave"
            ) {

                zoneRemove();

            } else if (
                event.type === "drop"
            ) {

                zoneRemove();

                appendImportItems(
                    await probePaths(
                        event.payload.paths
                    )
                );

                renderSelectedFiles();
            }
        }
    );
}


