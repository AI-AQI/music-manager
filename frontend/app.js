/* =========================================================
   获取音频时长
========================================================= */

function getAudioDuration(path) {

    return new Promise(resolve => {

        const url =
            convertFileSrc(path);

        const audio =
            document.createElement("audio");

        audio.preload = "metadata";

        audio.onloadedmetadata = () => {

            const duration =
                audio.duration;

            resolve(
                Number.isFinite(duration)
                    ? duration
                    : 0
            );
        };


        audio.onerror = () => {

            resolve(0);
        };


        audio.src = url;
    });
}


