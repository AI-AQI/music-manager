async function loadAndPlay(music, segment = null) {

    const p = state.player;

    const a = getAudio();

    // 队列中的对象可能是在 Finder 移动文件前生成的，播放前总是取最新地址。
    await invoke("sync_library_locations");
    music = (await dbGet("music", music.id)) || music;

    p.loading = true;

    p.music = music;

    p.segment = segment;

    renderBarMeta();

    showPlayerBar();

    try {

        const exists =
            await invoke("file_exists", {
                path: music.path
            });

        if (!exists) {

            p.loading = false;

            skipBroken(music);

            return;
        }

        const url =
            convertFileSrc(music.path);

        if (p.currentUrl === url) {

            if (segment) {

                a.currentTime = segment.start;

            } else {

                a.currentTime = 0;
            }

        } else {

            p.currentUrl = url;

            a.src = url;
        }

        if (segment) {

            const handleMeta = () => {

                a.removeEventListener(
                    "loadedmetadata",
                    handleMeta
                );

                a.currentTime = segment.start;

                updateBarTime();
            };

            a.addEventListener(
                "loadedmetadata",
                handleMeta
            );
        }

        try {

            await a.play();

            setPlayingUI(true);

        } catch (error) {

            /*
             * 自动播放可能被拦:
             * 停在"已加载未播放"状态,等用户点 ▶
             */

            setPlayingUI(false);
        }

    } catch (error) {

        console.error(error);

        showToast(
            "文件无法访问，可能已经被移动或删除"
        );

    } finally {

        p.loading = false;
    }
}


function onSegmentTimeupdate() {

    const p = state.player;

    const a = getAudio();

    if (
        !p.segment ||
        !a.duration
    ) {
        return;
    }

    if (
        a.currentTime >=
        p.segment.end
    ) {

        a.pause();
        if (p.queueSource === "candidates") {
            nextTrack(true);
        } else {
            setPlayingUI(false);
            a.currentTime = p.segment.start;
        }
    }
}


async function playMusic(id, opts = {}) {

    const p = state.player;

    const music =
        await dbGet("music", id);

    if (!music) {
        return;
    }

    const source =
        opts.source || "view";

    if (source === "candidates") {

        p.queue =
            p.candidates.slice();

        p.queueSource =
            "candidates";

        p.index =
            p.queue.findIndex(
                m => m.id === id
            );

    } else {

        p.queue =
            visibleQueueMusic.slice();

        p.queueSource = "view";

        p.index =
            p.queue.findIndex(
                m => m.id === id
            );

        if (p.index === -1) {

            /*
             * 点击的音乐不在当前可见队列
             * (如详情/候选里点播)
             * 单独作为一首播放,不绑定队列
             */

            p.queue = [];
            p.index = -1;
        }
    }

    updateBarControls();

    await loadAndPlay(music);
}


async function playClip(clip, opts = {}) {

    const currentClip = clip?.id
        ? await dbGet("clips", clip.id)
        : null;
    if (currentClip) clip = currentClip;

    const music =
        await dbGet("music", clip.musicId);

    if (!music) {
        return;
    }

    const p = state.player;

    if (opts.source === "candidates") {
        p.queue = p.candidates.slice();
        p.queueSource = "candidates";
        p.index = p.queue.findIndex(item => item.id === clip.id);
    } else {
        p.queue = [];
        p.queueSource = "clip";
        p.index = -1;
    }

    p.segment = {
        start: clip.start,
        end: clip.end,
        musicId: clip.musicId,
        clipId: clip.id
    };

    updateBarControls();

    await loadAndPlay(music, p.segment);
}


async function togglePlay() {

    const p = state.player;

    const a = getAudio();

    if (!p.music) {
        return;
    }

    if (a.paused) {

        try {

            await a.play();

            setPlayingUI(true);

        } catch (error) {

            showToast(
                "播放被浏览器拦截，请重试"
            );
        }

    } else {

        a.pause();

        setPlayingUI(false);
    }
}


async function nextTrack(auto = false) {

    const p = state.player;

    if (!p.queue.length) {
        return;
    }

    const max =
        p.queue.length - 1;

    if (p.index >= max) {

        if (!auto) {

            showToast("已是最后一首");
        }

        return;
    }

    p.index++;

    updateBarControls();

    const item = p.queue[p.index];
    if (item.kind === "clip") await playClip(item, { source: "candidates" });
    else await playMusic(item.id, { source: "candidates" });
}


async function prevTrack() {

    const p = state.player;

    if (!p.queue.length) {
        return;
    }

    if (p.index <= 0) {

        showToast("已是第一首");

        return;
    }

    p.index--;

    updateBarControls();

    const item = p.queue[p.index];
    if (item.kind === "clip") await playClip(item, { source: "candidates" });
    else await playMusic(item.id, { source: "candidates" });
}


