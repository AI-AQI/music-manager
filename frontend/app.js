function initPlayer() {

    const a =
        getAudio();

    a.addEventListener(
        "loadedmetadata",
        () => {

            updateBarTime();
        }
    );

    a.addEventListener(
        "timeupdate",
        () => {

            if (
                !state.player.seeking
            ) {

                updateBarTime();

                onSegmentTimeupdate();
            }
        }
    );

    a.addEventListener(
        "ended",
        () => {

            nextTrack(true);
        }
    );

    a.addEventListener(
        "error",
        () => {

            const p = state.player;

            if (p.music) {

                const broken = p.music;

                p.currentUrl = "";

                skipBroken(broken);
            }
        }
    );

    $("playerPlayBtn").addEventListener(
        "click",
        togglePlay
    );

    $("playerNextBtn").addEventListener(
        "click",
        () => nextTrack(false)
    );

    $("playerPrevBtn").addEventListener(
        "click",
        prevTrack
    );

    $("playerCloseBtn").addEventListener(
        "click",
        clearPlayer
    );

    $("playerTitle").addEventListener(
        "click",
        () => {

            const p = state.player;

            if (p.music) {

                openDetail(
                    p.music.id
                );
            }
        }
    );

    $("playerAddCandidateBtn").addEventListener(
        "click",
        async () => {

            const p = state.player;

            if (p.segment?.clipId) {
                await toggleClipCandidate(p.segment.clipId);
            } else if (p.music) {
                await addCandidate(p.music);
            }
        }
    );

    $("playerCandidatesBtn").addEventListener(
        "click",
        () => {

            if (
                $("candidatePanel").classList
                    .contains("hidden")
            ) {

                openCandidatePanel();

            } else {

                closeCandidatePanel();
            }
        }
    );

    $("openCandidatePanelBtn").addEventListener(
        "click",
        () => {
            if ($("candidatePanel").classList.contains("hidden")) {
                openCandidatePanel();
            } else {
                closeCandidatePanel();
            }
        }
    );

    $("closeCandidatePanel").addEventListener(
        "click",
        closeCandidatePanel
    );

    $("clearCandidatesBtn").addEventListener(
        "click",
        clearCandidates
    );

    $("playerSeek").addEventListener(
        "input",
        event => {

            const p = state.player;

            const audio = getAudio();

            p.seeking = true;

            if (audio.duration) {

                audio.currentTime =
                    event.target.value /
                    1000 *
                    audio.duration;
            }

            updateBarTime();
        }
    );

    $("playerSeek").addEventListener(
        "change",
        () => {

            state.player.seeking = false;
        }
    );
}


