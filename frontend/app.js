async function revealInFinder(music) {

    if (!music.path) {

        showToast(
            "这个音乐没有关联文件路径"
        );

        return;
    }

    try {

        const exists =
            await invoke("file_exists", {
                path: music.path
            });

        if (!exists) {

            showToast(
                "文件不存在，可能已经被移动或删除"
            );

            return;
        }

        await __TAURI__.opener.revealItemInDir(
            music.path
        );

    } catch (error) {

        console.error(error);

        showToast(
            "无法在 Finder 中定位"
        );
    }
}


