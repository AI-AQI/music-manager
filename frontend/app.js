/* =========================================================
   搜索
========================================================= */

function matchesSearch(music, clips, query) {

    if (!query) {
        return true;
    }

    query = query.toLowerCase();

    const musicText = [

        music.name,
        music.fileName,
        music.album,
        music.artist,
        music.genre,
        music.year,
        music.path,
        ...(music.tags || [])

    ]
        .join(" ")
        .toLowerCase();


    if (musicText.includes(query)) {
        return true;
    }


    for (const clip of clips) {

        const clipText = [

            clip.name,
            ...(clip.tags || [])

        ]
            .join(" ")
            .toLowerCase();

        if (clipText.includes(query)) {
            return true;
        }
    }

    return false;
}


