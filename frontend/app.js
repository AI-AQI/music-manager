async function reauthorizeFile(music) {

    try {

        const selected =
            await __TAURI__.dialog.open({
                multiple: false,
                filters: [
                    {
                        name: "音频文件",
                        extensions: [
                            "mp3",
                            "wav",
                            "flac",
                            "m4a",
                            "aac",
                            "ogg",
                            "opus"
                        ]
                    }
                ]
            });

        if (!selected) {

            return;
        }


        const path =
            String(selected);

        const info =
            await invoke("probe_file", {
                path
            });

        if (!info.exists) {

            showToast("选中的文件不存在");

            return;
        }


        music.path = info.path;

        music.fileName = info.fileName;

        music.name = info.name;

        music.fileSize = info.fileSize;

        music.mimeType = info.mimeType;

        try {

            music.duration =
                await getAudioDuration(
                    info.path
                );

        } catch (error) {

            console.log(error);
        }

        music.updatedAt = Date.now();


        await dbPut(
            "music",
            music
        );


        showToast("原文件已经重新绑定");

        await openDetail(music.id);

    } catch (error) {

        console.error(error);
    }
}


