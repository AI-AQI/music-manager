async function renderDetailTagSuggestions(query = "") {

    const container =
        $("detailTagSuggestions");

    const allTags = await getAllTags();

    const used =
        new Set(state.editTags);

    let suggestions =
        allTags.filter(
            tag =>
                !used.has(tag) &&
                (!query ||
                    tag.toLowerCase()
                        .includes(
                            query.toLowerCase()
                        ))
        );

    if (!suggestions.length) {

        container.innerHTML = "";

        return;
    }

    container.innerHTML =
        `<div class="suggestion-title">已有 Tag</div>` +
        suggestions
            .map(tag => `

                <button
                    class="suggestion-tag"
                    data-detail-suggest-tag="${escapeHTML(tag)}"
                >
                    #${escapeHTML(tag)}
                </button>

            `)
            .join("");
}


function addDetailEditTag() {

    const input =
        $("detailEditTagInput");

    const value = normalizeTag(input.value);

    if (!value) {
        return;
    }

    if (
        !state.editTags.includes(value)
    ) {

        state.editTags.push(value);
    }

    input.value = "";

    renderDetailEditTags();
}


async function saveDetailEdit(changes) {

    const id =
        state.selectedMusic.id;

    const music =
        await dbGet("music", id);

    if (!music) {
        return;
    }

    if (changes.name !== undefined) {

        music.name =
            changes.name;
    }

    if (changes.album !== undefined) {

        music.album =
            changes.album;
    }

    if (changes.artist !== undefined) {

        music.artist =
            changes.artist;
    }

    if (changes.genre !== undefined) {

        music.genre =
            changes.genre;
    }

    if (changes.year !== undefined) {

        music.year =
            changes.year;
    }

    if (changes.tags !== undefined) {

        music.tags =
            changes.tags;
    }

    music.updatedAt =
        Date.now();

    await dbPut("music", music);


    /* 同步播放器 */

    const p = state.player;

    if (
        p.music &&
        p.music.id === music.id
    ) {

        p.music = music;

        renderBarMeta();
    }


    /* 刷新 */

    await updateCounts();

    await renderSidebarTags();

    await render();

    await openDetail(music.id);

    showToast("已保存");
}


