/* =========================================================
   目录视图（专辑 / Tags）
   左侧分类列表 + 右侧对应音乐
========================================================= */

function renderCatalogView(music, clips, type) {

    music = music.filter(item => {
        const itemClips = clips.filter(clip => clip.musicId === item.id);
        return matchesSearch(item, itemClips, state.search) && matchesActiveTags(item, itemClips);
    });

    $("resultInfo").textContent = `${music.length} 个音乐`;

    const cand =
        new Set(
            state.player.candidates
                .map(c => c.id)
        );


    /* 构建分组 */

    let entries = [];

    if (type === "tag") {

        const musicById =
            new Map(
                music.map(m => [m.id, m])
            );

        const map = new Map();

        const pushTag = (tag, m) => {

            if (!map.has(tag)) {
                map.set(tag, new Set());
            }

            map.get(tag).add(m.id);
        };

        music.forEach(m => {

            (m.tags || []).forEach(
                tag => pushTag(tag, m)
            );
        });

        clips.forEach(c => {

            const m = musicById.get(c.musicId);

            if (!m) {
                return;
            }

            (c.tags || []).forEach(
                tag => pushTag(tag, m)
            );
        });

        entries = [...map.entries()].map(
            ([tag, idSet]) => ({

                key: tag,
                items: [...idSet]
                    .map(id => musicById.get(id))
                    .filter(Boolean)
            })
        );

    } else {

        const emptyLabel = "未设置专辑";

        const map = new Map();

        music.forEach(m => {

            const key =
                (m.album || "").trim() ||
                emptyLabel;

            if (!map.has(key)) {
                map.set(key, []);
            }

            map.get(key).push(m);
        });

        entries = [...map.entries()].map(
            ([key, items]) => ({ key, items })
        );
    }


    entries.sort(
        (a, b) =>
            a.key.localeCompare(
                b.key,
                "zh-CN"
            )
    );


    if (!entries.length) {

        $("contentArea").innerHTML = `
            <div class="empty-state">
                <div class="empty-icon">
                    ${type === "tag" ? "#" : "♫"}
                </div>
                <div class="empty-title">
                    ${
                        type === "tag"
                            ? "还没有 Tag"
                            : "还没有专辑"
                    }
                </div>
                <div class="empty-description">
                    ${
                        type === "tag"
                            ? "在音乐详情或片段里给音乐添加 Tag"
                            : "导入音乐后填写专辑信息即可归档"
                    }
                </div>
            </div>
        `;

        visibleQueueMusic = [];
        renderSelectionToolbar();
        syncPlayerQueue();

        return;
    }


    /* 选中项 */

    let selected = state.catalogSelection;

    if (
        !selected ||
        !entries.some(e => e.key === selected)
    ) {

        selected = entries[0].key;
    }

    state.catalogSelection = selected;

    const current =
        entries.find(e => e.key === selected);


    /* 左侧目录 */

    const listHTML = entries
        .map(e => `

            <button
                class="catalog-item ${
                    e.key === selected ? "active" : ""
                }"
                data-catalog-key="${escapeHTML(e.key)}"
            >

                <span class="catalog-item-icon">
                    ${
                        type === "tag"
                            ? "#"
                            : type === "album"
                                ? "▣"
                                : "▤"
                    }
                </span>

                <span class="catalog-item-name">
                    ${escapeHTML(e.key)}
                </span>

                <span class="catalog-item-count">
                    ${e.items.length}
                </span>

            </button>
        `)
        .join("");


    /* 右侧音乐列表 */

    const rowsHTML = current.items
        .map(item => {

            const itemClips =
                clips.filter(
                    c => c.musicId === item.id
                );

            const tags =
                item.tags || [];

            return `

                <div
                    class="music-row ${state.selectedMusicIds.has(item.id) ? "is-selected" : ""}"
                    data-music-id="${item.id}"
                >

                    ${state.selectionMode ? `<label class="music-select"><input type="checkbox" data-select-music="${item.id}" ${state.selectedMusicIds.has(item.id) ? "checked" : ""}><span></span></label>` : ""}

                    <div class="music-icon">${musicArtwork(item)}</div>

                    <div class="music-main">

                        <div class="music-name">
                            ${escapeHTML(item.name)}
                        </div>

                        <div class="music-meta">

                            ${
                                type !== "album" &&
                                item.album
                                    ? `<span>专辑：${escapeHTML(item.album)}</span>`
                                    : ""
                            }

                            <span>
                                ${formatTime(item.duration)}
                            </span>

                            ${
                                itemClips.length
                                    ? `<span>◈ ${itemClips.length} 个片段</span>`
                                    : ""
                            }

                        </div>

                        <div class="music-tags">

                            ${tags
                                .map(
                                    tag =>
                                        `<span class="tag">#${escapeHTML(tag)}</span>`
                                )
                                .join("")
                            }

                        </div>

                    </div>

                    <div class="music-actions">

                        <button
                            class="icon-action ${state.player.music?.id === item.id && state.player.playing ? "is-playing" : ""}"
                            data-action="play"
                            data-id="${item.id}"
                            title="${state.player.music?.id === item.id && state.player.playing ? "暂停试听" : "试听"}"
                        >
                            ${state.player.music?.id === item.id && state.player.playing ? "Ⅱ" : "▶"}
                        </button>

                        <button
                            class="icon-action ${
                                cand.has(item.id)
                                    ? "is-candidate"
                                    : ""
                            }"
                            data-action="candidate"
                            data-id="${item.id}"
                            title="${
                                cand.has(item.id)
                                    ? "移出候选"
                                    : "加入候选"
                            }"
                        >
                            ${
                                cand.has(item.id)
                                    ? "★"
                                    : "☆"
                            }
                        </button>

                        <button
                            class="icon-action info-strong"
                            data-action="info"
                            data-id="${item.id}"
                            title="详情"
                        >
                            ⓘ
                        </button>

                        <button
                            class="icon-action"
                            data-action="delete"
                            data-id="${item.id}"
                            title="删除"
                        >
                            🗑
                        </button>

                    </div>

                </div>
            `;

        })
        .join("");


    $("contentArea").innerHTML = `
        <div class="catalog-view">

            <div class="catalog-list">
                ${listHTML}
            </div>

            <div class="catalog-detail">

                <div class="catalog-detail-header">
                    <span class="catalog-detail-title">
                        ${escapeHTML(current.key)}
                    </span>
                    <span class="catalog-detail-count">
                        ${current.items.length} 首
                    </span>
                    ${type === "album" && current.key !== "未设置专辑" ? `<button class="text-btn danger-btn" data-delete-album="${escapeHTML(current.key)}">删除专辑</button>` : ""}
                </div>

                <div class="music-list">
                    ${rowsHTML}
                </div>

            </div>

        </div>
    `;

    visibleQueueMusic = current.items;
    renderSelectionToolbar();

    syncPlayerQueue();
}


