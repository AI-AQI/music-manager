function withTagWritePayload(value) {
    const tags = [...(value.tags || [])];
    const alignedIds = [...(value.tagIds || [])];
    return {
        ...value,
        tags,
        tagIds: alignedIds.filter(Number.isInteger),
        newTags: tags.filter((_, index) => !Number.isInteger(alignedIds[index]))
    };
}

